function openLaws() {
    const el = document.getElementById('lawsContent');
    if (!el) return;
    el.innerHTML = LAWS_DATA.map(cat => `
        <div style="margin-bottom:14px;">
            <div class="section-label" style="margin-bottom:8px;">${cat.cat}</div>
            ${cat.laws.map(law => `
                <div class="law-card">
                    <div class="law-title">📌 ${law.title}</div>
                    <div class="law-formula">${law.formula}</div>
                    <div class="law-desc">${law.desc}</div>
                    <div class="law-example">مثال: ${law.example}</div>
                </div>
            `).join('')}
        </div>
    `).join('');
    document.getElementById('lawsOverlay').classList.add('active');
}

function closeLaws() {
    document.getElementById('lawsOverlay').classList.remove('active');
}
